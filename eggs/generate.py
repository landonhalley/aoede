INSTALL_SCRIPT = f"""#!/bin/bash
# Aoede install script. Downloads the latest Aoede build; it also updates itself
# on every start, so reinstalling is never needed for updates.
set -e
mkdir -p /mnt/server
cd /mnt/server

REPO="${{GITHUB_REPO:-{REPO}}}"
BASE_URL="https://github.com/${{REPO}}/releases/download/latest"
case "$(uname -m)" in
    x86_64) ARCH=x86_64 ;;
    aarch64 | arm64) ARCH=aarch64 ;;
    *) echo "Unsupported architecture: $(uname -m)"; exit 1 ;;
esac

echo "Downloading Aoede from ${{REPO}}..."
curl --fail --silent --show-error --location "${{BASE_URL}}/aoede-linux-${{ARCH}}" -o aoede
chmod +x aoede
curl --fail --silent --show-error --location "${{BASE_URL}}/version.txt" -o .aoede-version
mkdir -p data
echo "Aoede installed."
"""

